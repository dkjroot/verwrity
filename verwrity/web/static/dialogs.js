"use strict";

const appDialog = document.querySelector("#app-dialog");
if (appDialog) {
  const form = appDialog.querySelector("[data-app-dialog-form]");
  const title = appDialog.querySelector("[data-app-dialog-title]");
  const message = appDialog.querySelector("[data-app-dialog-message]");
  const inputLabel = appDialog.querySelector("[data-app-dialog-input-label]");
  const input = appDialog.querySelector("[data-app-dialog-input]");
  const cancel = appDialog.querySelector("[data-app-dialog-cancel]");
  const accept = appDialog.querySelector("[data-app-dialog-accept]");
  // Build the optional control here so cached older dialog templates work too.
  const checkboxLabel = document.createElement("label");
  checkboxLabel.className = "app-dialog-checkbox"; checkboxLabel.hidden = true;
  const checkbox = document.createElement("input"); checkbox.type = "checkbox";
  checkbox.dataset.appDialogCheckbox = "";
  const checkboxText = document.createElement("span");
  checkboxLabel.append(checkbox, checkboxText);
  const checkboxDescription = document.createElement("p");
  checkboxDescription.id = "app-dialog-checkbox-description"; checkboxDescription.hidden = true;
  checkbox.setAttribute("aria-describedby", checkboxDescription.id);
  accept.closest(".app-dialog-actions").before(checkboxLabel, checkboxDescription);
  const queue = [];
  let active = null;

  function presentNext() {
    if (active || !queue.length) return;
    active = queue.shift();
    title.textContent = active.options.title || "Confirm action";
    message.textContent = active.message;
    const wantsInput = active.kind === "prompt";
    inputLabel.hidden = !wantsInput;
    input.hidden = !wantsInput;
    inputLabel.textContent = active.options.label || "Value";
    input.value = active.options.value || "";
    input.placeholder = active.options.placeholder || "";
    input.maxLength = active.options.maxLength || 1000;
    const wantsCheckbox = active.kind === "confirm-checkbox";
    checkboxLabel.hidden = !wantsCheckbox;
    checkbox.checked = wantsCheckbox && Boolean(active.options.checkbox?.checked);
    checkboxText.textContent = active.options.checkbox?.label || "";
    checkboxDescription.textContent = active.options.checkbox?.description || "";
    checkboxDescription.hidden = !wantsCheckbox || !checkboxDescription.textContent;
    cancel.hidden = active.kind === "alert";
    accept.textContent = active.options.acceptLabel || (active.kind === "alert" ? "OK" : "Continue");
    appDialog.showModal();
    (wantsInput ? input : accept).focus();
    if (wantsInput) input.select();
  }

  function finish(accepted) {
    if (!active) return;
    const completed = active;
    const value = input.value;
    active = null;
    appDialog.close();
    if (completed.kind === "prompt") completed.resolve(accepted ? value : null);
    else if (completed.kind === "confirm-checkbox") completed.resolve({ confirmed: accepted, checked: checkbox.checked });
    else completed.resolve(completed.kind === "alert" ? undefined : accepted);
    queueMicrotask(presentNext);
  }

  function request(kind, messageText, options = {}) {
    // The connection modal explains the recovery action. Do not cover it with
    // a second save-failure alert generated by the same transport failure.
    if (kind === "alert" && window.verwrityServerConnection?.unavailable) return Promise.resolve();
    return new Promise((resolve) => {
      queue.push({ kind, message: messageText, options, resolve });
      presentNext();
    });
  }

  form.addEventListener("submit", (event) => {
    event.preventDefault();
    finish(true);
  });
  cancel.addEventListener("click", () => finish(false));
  appDialog.querySelector("[data-app-dialog-close]").addEventListener("click", () => finish(false));
  appDialog.addEventListener("cancel", (event) => {
    event.preventDefault();
    finish(false);
  });

  window.verwrityDialog = {
    alert: (messageText, options) => request("alert", messageText, options),
    confirm: (messageText, options) => request("confirm", messageText, options),
    confirmWithCheckbox: (messageText, options) => request("confirm-checkbox", messageText, options),
    prompt: (messageText, options) => request("prompt", messageText, options),
  };
}

document.querySelectorAll("[data-confirm-remove]").forEach((removeForm) => removeForm.addEventListener("submit", async (event) => {
  if (removeForm.dataset.confirmed === "true") {
    delete removeForm.dataset.confirmed;
    return;
  }
  event.preventDefault();
  const confirmed = await window.verwrityDialog?.confirm("Remove this scene from the current storyboard? It will be kept as historical material.", {
    title: "Remove scene", acceptLabel: "Remove",
  });
  if (!confirmed) return;
  removeForm.dataset.confirmed = "true";
  removeForm.requestSubmit(event.submitter || undefined);
}));

document.querySelectorAll("[data-confirm-permanent-delete]").forEach((deleteForm) => deleteForm.addEventListener("submit", async (event) => {
  if (deleteForm.dataset.confirmed === "true") {
    delete deleteForm.dataset.confirmed;
    return;
  }
  event.preventDefault();
  const confirmed = await window.verwrityDialog?.confirm("Permanently delete this scene and its comments? This cannot be undone.", {
    title: "Delete scene permanently", acceptLabel: "Delete permanently",
  });
  if (!confirmed) return;
  deleteForm.dataset.confirmed = "true";
  deleteForm.requestSubmit(event.submitter || undefined);
}));

