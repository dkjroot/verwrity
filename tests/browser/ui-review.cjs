const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const fs = require('node:fs/promises');
const url = process.env.VERWRITY_TEST_URL || 'http://127.0.0.1:8766';
(async () => {
  const browser = await chromium.launch({ headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    page.setDefaultTimeout(8000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    assert.equal((await (await page.request.get(`${url}/__browser_test__`)).json()).isolated, true);
    await page.request.post(`${url}/__browser_test__/reset`);
    await page.goto(url); await page.waitForFunction(() => window.verwrityEditor);
    await page.evaluate(() => document.querySelector('#start-dialog')?.close());
    assert.equal(await page.locator('.footer, [data-footer-toggle]').count(), 0);
    assert.equal(await page.locator('.display-options [data-writing-mode-label]').innerText(), 'Normal mode');
    assert.equal(await page.locator('.editor-toolbar > details').first().locator('summary').innerText(), 'View');
    assert.equal(await page.locator('.view-menu [data-paragraph-indentation]').count(), 1);
    assert.equal(await page.locator('.view-menu [data-manuscript-setting]').count(), 4);
    assert.equal(await page.locator('.project-question-dock [data-manuscript-task]').count(), 0);
    assert(await page.locator('.editor-toolbar [data-manuscript-task]').count());
    assert.equal(await page.locator('.spelling-dictionary-manager').count(), 0);
    const artifacts = process.env.VERWRITY_TEST_ARTIFACT_ROOT || path.resolve('agent_docs/ui-review-screenshots'); await fs.mkdir(artifacts, { recursive: true });
    await page.screenshot({ path: path.join(artifacts, 'workspace.png') });
    const menu = async name => { const summary = page.locator(`${name} > summary`); if (!await summary.evaluate(el => el.parentElement.open)) await summary.click(); };
    await menu('.settings-menu'); await page.locator('[data-open-project-words]').click();
    const words = page.locator('.project-words-dialog'); await words.waitFor();
    await words.locator('[data-words-edit]').click();
    await words.locator('[data-words-project]').fill('Qelvar\nMaridel');
    await words.locator('[data-words-edit]').click();
    await words.locator('[data-words-global]').fill('starling');
    await words.locator('[data-words-save]').click();
    await page.waitForFunction(() => document.querySelector('[data-words-status]').textContent === 'Word lists saved.');
    let state = await (await page.request.get(`${url}/project/words`)).json(); assert(state.curated.includes('Qelvar'));
    await words.locator('[data-words-selection] input[value="Qelvar"]').check(); await words.locator('[data-words-move]').click();
    await words.locator('[data-words-save]').click();
    await page.waitForFunction(() => !document.querySelector('[data-words-save]').disabled);
    state = await (await page.request.get(`${url}/project/words`)).json(); assert(!state.words.includes('Qelvar'));
    assert((await (await page.request.get(`${url}/spelling-dictionary/global`)).json()).words.includes('qelvar'));
    await words.locator('[data-words-close]').click();
    await menu('.settings-menu'); await page.locator('[data-ai-models-open]').click();
    await page.waitForFunction(() => document.querySelector('[data-ai-settings-status]').textContent === '');
    assert.equal(await page.locator('[data-voice-preset]').count(), 3);
    await page.selectOption('[data-voice-preset="voice"]', 'bf_emma'); assert.equal(await page.locator('[name=voice]').inputValue(), 'bf_emma');
    await page.locator('[data-ai-tab="stt"]').click(); assert(await page.locator('[name=language] option').count() > 20);
    assert.equal(await page.locator('[data-stt-model-folder-help]').isVisible(), false);
    assert.equal(await page.locator('[data-ocr-model-cancel]').isVisible(), false);
    const audio = await page.request.get(`${url}/static/speech-test.wav`); assert.equal(audio.status(), 200); assert.equal((await audio.body()).subarray(0, 4).toString(), 'RIFF');
    await page.screenshot({ path: path.join(artifacts, 'speech-settings.png') });
    await page.locator('[data-ai-models-close]').click();
    await page.evaluate(() => document.querySelector('[data-draft-open]').click());
    await page.locator('#dictate-draft-dialog').waitFor();
    assert.equal(await page.locator('[data-draft-combined], [data-draft-buffers], [data-draft-suggest]').count(), 0);
    assert.equal(await page.locator('[data-draft-cancel]').isDisabled(), true);
    await page.locator('[data-draft-vocabulary]').fill('Maridel, moonwyrm');
    await page.locator('[data-draft-vocabulary]').blur();
    await page.screenshot({ path: path.join(artifacts, 'dictate-draft.png') });
    await page.locator('#dictate-draft-dialog [data-draft-hide]').first().click();
    await page.evaluate(() => document.querySelector('[data-ocr-open]').click());
    try { await page.locator('#ocr-import-dialog').waitFor(); }
    catch (error) { console.error('OCR open diagnostics:', errors, await page.locator('#app-dialog-message').textContent()); throw error; }
    assert.equal(await page.locator('[data-ocr-clean-all]').isDisabled(), true);
    assert.equal(await page.locator('[data-ocr-manage], [data-ocr-configure], [data-ocr-profile-stop]').count(), 0);
    await page.locator('[data-ocr-vocabulary]').fill('Maridel, moonwyrm');
    await page.screenshot({ path: path.join(artifacts, 'ocr-import.png') });
    await page.locator('#ocr-import-dialog [data-ocr-hide]').first().click();
    if (!await page.locator('#wiki-panel').isVisible()) await page.locator('[data-panel-toggle=wiki]').click();
    await page.locator('#wiki-search').fill('Project notes'); await page.locator('.wiki-page-list .wiki-link').filter({ hasText: 'Project notes' }).first().click();
    assert.equal(await page.locator('#wiki-search').inputValue(), ''); assert.equal(await page.locator('.wiki-page-list').isVisible(), false);
    assert.equal(await page.locator('[data-wiki-current-page] mark').count(), 0);
    const current = page.locator('[data-wiki-current-page]'); await current.getByRole('button', { name: 'Edit page', exact: true }).click();
    assert.equal(await page.locator('#wiki-search').isVisible(), false); assert.equal(await page.locator('[data-wiki-new]').isVisible(), false);
    const editor = page.locator('[data-wiki-page-editor]');
    await editor.getByRole('button', { name: 'Suggest purpose (AI)', exact: true }).waitFor();
    const body = editor.locator('textarea[name=body]'); await body.fill('Human review test.');
    await editor.locator('details.wiki-template-menu > summary').click(); await editor.locator('input[name=title]').click();
    assert.equal(await editor.locator('.wiki-template-menu').evaluate(el => el.open), false);
    await body.evaluate(el => { el.focus(); el.setSelectionRange(0, el.value.length); el.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: 900, clientY: 450 })); });
    await page.locator('.wiki-ownership-menu').getByRole('menuitem', { name: 'Mark as AI maintained', exact: true }).click();
    assert(await editor.locator('[name=authorship_edits]').inputValue());
    await page.screenshot({ path: path.join(artifacts, 'wiki-editor.png') });
    await page.keyboard.press('Control+s'); await page.locator('#app-dialog').waitFor();
    assert.match(await page.locator('#app-dialog-message').innerText(), /wiki page/);
    await page.locator('#app-dialog [data-app-dialog-accept]').click();
    await page.waitForFunction(() => !document.querySelector('[data-save-project]').disabled);
    assert.equal(await body.inputValue(), 'Human review test.'); assert.equal(await page.evaluate(() => window.verwrityWiki.hasPending()), false);
    await editor.getByRole('button', { name: 'Cancel edit', exact: true }).click();
    assert(await current.locator('.wiki-block-source').count()); await current.locator('.wiki-block-source').first().click();
    await page.locator('dialog[aria-label="AI permission"]').waitFor(); await page.locator('[aria-label="Close AI source"]').click();
    // Preserve a reading position through focus transitions without moving the caret.
    await page.locator('[data-editor-viewport]').evaluate(el => { el.scrollTop = 800; });
    const before = await page.locator('[data-editor-viewport]').evaluate(el => el.scrollTop);
    await menu('.focus-menu'); await page.locator('[data-standard-focus-toggle]').click();
    await page.locator('.writing-restore-controls > summary').click(); await page.locator('[data-exit-focus]').click();
    await page.waitForTimeout(150);
    assert(Math.abs((await page.locator('[data-editor-viewport]').evaluate(el => el.scrollTop)) - before) < 100);
    const sceneId = await page.locator('[data-rich-editor]').getAttribute('data-scene-id');
    await page.locator('[data-storyboard-link]').click();
    const note = page.locator(`[data-story-note][data-scene-id="${sceneId}"]`);
    await page.waitForFunction(() => document.querySelector('[data-note-title]')?.ondblclick);
    assert.equal(await page.locator('.footer').count(), 0);
    await note.locator('[data-note-title]').dblclick();
    await note.locator('[data-note-title-input]').fill('UI review title');
    await note.locator('[data-note-title-input]').press('Enter');
    await note.locator('[data-note-color]').fill('#405090');
    await page.locator('[data-board-save]').click();
    await page.waitForFunction(() => window.verwrityEditor);
    const row = page.locator(`.scene-row[data-scene-id="${sceneId}"]`);
    assert.equal(await row.locator('.scene').innerText(), 'UI review title');
    const colours = await row.evaluate(el => ({ background: getComputedStyle(el).backgroundColor, ink: getComputedStyle(el.querySelector('.scene')).color, outline: getComputedStyle(el).outlineStyle }));
    assert.equal(colours.background, 'rgb(64, 80, 144)'); assert.equal(colours.ink, 'rgb(255, 255, 255)'); assert.equal(colours.outline, 'solid');
    await page.setViewportSize({ width: 1366, height: 620 });
    await page.screenshot({ path: path.join(artifacts, 'laptop-colour-selection.png') });
    await page.locator('[data-theme-toggle]').click();
    await page.screenshot({ path: path.join(artifacts, 'laptop-light.png') });
    assert.deepEqual(errors, []);
    console.log('PASS: UI review — toolbar, word-list moves, settings, import dialogs, wiki editing/save/context/evidence, menu dismissal, focus position and screenshots.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
